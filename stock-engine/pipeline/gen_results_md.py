"""Generate RESULTS.md from outputs/tables/*.json — ensures README/paper numbers match data."""
from __future__ import annotations

import json
import sys
from pathlib import Path

TABLES_DIR = Path("outputs/tables")
OUT_FILE = Path("RESULTS.md")


def format_value(v):
    if isinstance(v, float):
        return f"{v:.6f}"
    return str(v)


def main():
    if not TABLES_DIR.exists():
        print("ERROR: outputs/tables not found")
        return 1

    json_files = sorted(TABLES_DIR.glob("*.json"))
    if not json_files:
        print("ERROR: No JSON files found in outputs/tables/")
        return 1

    lines = [
        "# Auto-Generated Results from outputs/tables/",
        "",
        "> **Do not edit this file directly.** It is generated by `pipeline/gen_results_md.py`.",
        "> Run `python pipeline/gen_results_md.py` after any pipeline step that writes to outputs/tables/.",
        "",
        "---",
        "",
    ]

    for jf in json_files:
        lines.append(f"## {jf.name}")
        lines.append("")

        try:
            data = json.loads(jf.read_text(encoding="utf-8"))
        except Exception as e:
            lines.append(f"*Error reading {jf.name}: {e}*")
            lines.append("")
            continue

        if isinstance(data, dict):
            for key, val in data.items():
                if key.startswith("_"):
                    lines.append(f"- **{key}**: {format_value(val)}")
                    continue
                if isinstance(val, (dict, list)):
                    lines.append(f"- **{key}**: {json.dumps(val, indent=2)[:500]}...")
                else:
                    lines.append(f"- **{key}**: {format_value(val)}")
        elif isinstance(data, list):
            lines.append(f"- List with {len(data)} items")
            if data and isinstance(data[0], dict):
                lines.append(f"  First item keys: {list(data[0].keys())}")
        lines.append("")

    OUT_FILE.write_text("\n".join(lines), encoding="utf-8")
    print(f"Generated {OUT_FILE}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
